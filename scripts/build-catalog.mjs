// Normalises data/ucc-catalog.json (researched from admissions.ucc.edu.gh)
// into the app's demo catalogue and a Supabase seed file.
//   node scripts/build-catalog.mjs
import { readFile, writeFile } from 'node:fs/promises'

const SOURCE = 'data/ucc-catalog.json'
const DEMO_OUT = 'src/data/demo/catalog.json'
const SQL_OUT = 'supabase/seed.sql'

const COLLEGE_COLORS = { CHLS: 'ember', CES: 'sky', CANS: 'lime', CoHAS: 'rose', CoDE: 'violet', UNI: 'gold' }
const SHORT_AWARDS = { Certificate: 1, Diploma: 2, PGCert: 1, PGDip: 1 }
const LONG_AWARDS = { 'MB ChB': 6, PharmD: 6, OD: 6 }

const slug = (text) =>
  text
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-')

function uniqueId(base, taken) {
  let id = base
  for (let n = 2; taken.has(id); n += 1) id = `${base}-${n}`
  taken.add(id)
  return id
}

function awardLevel(program) {
  if (program.level === 'postgraduate') return 'postgraduate'
  return program.degree in SHORT_AWARDS ? 'diploma' : 'undergraduate'
}

function levelsFor(program, courseLevels) {
  const levels = new Set(courseLevels ?? [])
  if (program.level === 'postgraduate') {
    if (!levels.size) levels.add(program.degree === 'PhD' ? 900 : 800)
  } else {
    const years = program.durationYears ?? SHORT_AWARDS[program.degree] ?? LONG_AWARDS[program.degree] ?? 4
    for (let i = 1; i <= years; i += 1) levels.add(i * 100)
  }
  return [...levels].sort((a, b) => a - b)
}

const raw = JSON.parse(await readFile(SOURCE, 'utf8'))

const courseLevelsByProgram = new Map()
for (const c of raw.courses) {
  const set = courseLevelsByProgram.get(c.program) ?? new Set()
  set.add(c.level)
  courseLevelsByProgram.set(c.program, set)
}

const colleges = []
const departments = []
const programs = []
const programIdByName = new Map()
const ids = new Set()

raw.colleges.forEach((college, sort) => {
  const collegeId = slug(college.short)
  colleges.push({
    id: collegeId,
    name: college.name,
    short: college.short,
    color: COLLEGE_COLORS[college.short] ?? 'gold',
    sort,
  })
  for (const faculty of college.faculties) {
    for (const dept of faculty.departments) {
      const departmentId = uniqueId(`${collegeId}-${slug(dept.name.replace(/^Department of /i, ''))}`, ids)
      departments.push({ id: departmentId, collegeId, faculty: faculty.name, name: dept.name })
      for (const program of dept.programs ?? []) {
        const id = uniqueId(slug(program.name), ids)
        if (!programIdByName.has(program.name)) programIdByName.set(program.name, id)
        programs.push({
          id,
          departmentId,
          collegeId,
          name: program.name,
          degree: program.degree,
          awardLevel: awardLevel(program),
          levels: levelsFor(program, courseLevelsByProgram.get(program.name)),
        })
      }
    }
  }
})

const courses = new Map()
const curriculum = []
const seenRows = new Set()
const unmatched = new Set()
for (const c of raw.courses) {
  const programId = programIdByName.get(c.program)
  if (!programId) {
    unmatched.add(c.program)
    continue
  }
  const courseId = slug(c.code)
  if (!courses.has(courseId)) {
    courses.set(courseId, { id: courseId, code: c.code, title: c.title, creditHours: c.creditHours ?? null, description: null })
  }
  const key = `${programId}|${courseId}`
  if (seenRows.has(key)) continue
  seenRows.add(key)
  curriculum.push({ programId, courseId, level: c.level, semester: c.semester === 2 ? 2 : 1 })
}

const catalog = { colleges: colleges.map(({ sort: _s, ...c }) => c), departments, programs, courses: [...courses.values()], curriculum }
await writeFile(DEMO_OUT, JSON.stringify(catalog))

// ---------- SQL seed ----------
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const values = (rows, fn) => rows.map((r) => `  (${fn(r).join(', ')})`).join(',\n')
const sql = `-- Generated by scripts/build-catalog.mjs from ${SOURCE}. Do not edit by hand.
begin;
insert into public.colleges (id, name, short, color, sort) values
${values(colleges, (c) => [q(c.id), q(c.name), q(c.short), q(c.color), q(c.sort)])}
on conflict (id) do update set name = excluded.name, short = excluded.short, color = excluded.color, sort = excluded.sort;

insert into public.departments (id, college_id, faculty, name) values
${values(departments, (d) => [q(d.id), q(d.collegeId), q(d.faculty), q(d.name)])}
on conflict (id) do update set faculty = excluded.faculty, name = excluded.name;

insert into public.programs (id, department_id, college_id, name, degree, award_level, levels) values
${values(programs, (p) => [q(p.id), q(p.departmentId), q(p.collegeId), q(p.name), q(p.degree), q(p.awardLevel), `'{${p.levels.join(',')}}'`])}
on conflict (id) do update set name = excluded.name, degree = excluded.degree, award_level = excluded.award_level, levels = excluded.levels;

insert into public.courses (id, code, title, credit_hours) values
${values([...courses.values()], (c) => [q(c.id), q(c.code), q(c.title), q(c.creditHours)])}
on conflict (id) do update set title = excluded.title, credit_hours = excluded.credit_hours;

insert into public.program_courses (program_id, course_id, level, semester) values
${values(curriculum, (r) => [q(r.programId), q(r.courseId), q(r.level), q(r.semester)])}
on conflict (program_id, course_id) do update set level = excluded.level, semester = excluded.semester;
commit;
`
await writeFile(SQL_OUT, sql)

console.log(
  `colleges ${colleges.length}, departments ${departments.length}, programmes ${programs.length}, courses ${courses.size}, curriculum rows ${curriculum.length}`,
)
if (unmatched.size) console.warn(`courses for unknown programmes skipped: ${[...unmatched].join('; ')}`)
