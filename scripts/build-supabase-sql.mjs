// Builds the Supabase SQL from the shared sample content:
//   supabase/seed-content.sql   sample people, discussions, votes, materials, past questions
//   supabase/setup.sql          migrations + catalogue + sample content, for a fresh project's SQL editor
//   node scripts/build-supabase-sql.mjs        (Node 23.6+, which loads .ts files directly)
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { A, MATERIALS, PAST_QUESTIONS, THREADS } from '../src/data/seed/content.ts'

/** Sample accounts use a reserved domain: no real person can own these addresses, and nobody can sign in as them. */
export const SAMPLE_DOMAIN = 'sample.nexa.invalid'
const MAX_VOTES_PER_POST = 12

const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replaceAll("'", "''")}'`)
const userId = (key) => `md5(${q(`nexa-sample-user:${key}`)})::uuid`
const rowId = (id) => `md5(${q(`nexa-sample:${id}`)})::uuid`
const ago = (hours) => `now() - interval '${Number(hours)} hours'`

const authors = Object.values(A)
const oldest = Math.max(...THREADS.map((t) => t.hours), ...MATERIALS.map((m) => m.hours), ...PAST_QUESTIONS.map((p) => p.hours))

function usersSql() {
  const rows = authors.map(
    (a, i) => `  ('00000000-0000-0000-0000-000000000000', ${userId(a.key)}, 'authenticated', 'authenticated', ${q(`${a.key}@${SAMPLE_DOMAIN}`)}, '',
   ${ago(oldest + 200 + i * 7)}, '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: a.name, role: a.role }))},
   ${ago(oldest + 200 + i * 7)}, now(), '', '', '', '')`,
  )
  const verify = authors.map(
    (a) =>
      `update public.profiles set role = ${q(a.role)}, is_verified = ${a.verified}, verified_via = ${a.verified ? "'moderator'" : 'null'} where id = ${userId(a.key)};`,
  )
  return `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values
${rows.join(',\n')}
on conflict (id) do nothing;

-- Sample accounts aren't on a UCC domain, so their badges are set directly.
${verify.join('\n')}`
}

function postRow(post, course, parentId) {
  const rating = 'rating' in post && post.rating ? post.rating : null
  return `  (${rowId(post.id)}, ${q(course)}, ${parentId ? rowId(parentId) : 'null'}, ${userId(post.by.key)}, ${q(post.body)}, ${rating ?? 'null'}, ${ago(post.hours)})`
}

function votesFor(post, index) {
  const voters = authors.filter((a) => a.key !== post.by.key)
  const count = Math.min(post.score ?? 0, voters.length, MAX_VOTES_PER_POST)
  return Array.from({ length: count }, (_, i) => `  (${rowId(post.id)}, ${userId(voters[(index + i) % voters.length].key)}, 1)`)
}

function postsSql() {
  const top = THREADS.map((t) => postRow(t, t.course, null))
  const replies = THREADS.flatMap((t) => (t.replies ?? []).map((r) => postRow(r, t.course, t.id)))
  const all = THREADS.flatMap((t) => [t, ...(t.replies ?? [])])
  const votes = all.flatMap((post, i) => votesFor(post, i))
  const insert = (rows) => `insert into public.posts (id, course_id, parent_id, author_id, body, rating, created_at) values
${rows.join(',\n')}
on conflict (id) do nothing;`
  return `${insert(top)}

${insert(replies)}

insert into public.post_votes (post_id, user_id, value) values
${votes.join(',\n')}
on conflict do nothing;`
}

function filesSql() {
  const materials = MATERIALS.map(
    (m) => `  (${rowId(m.id)}, ${q(m.course)}, ${q(m.kind)}, ${q(m.title)}, ${q(m.url)}, ${q(m.mimeType)}, ${userId(m.by.key)}, ${ago(m.hours)})`,
  )
  const papers = PAST_QUESTIONS.map(
    (p) =>
      `  (${rowId(p.id)}, ${q(p.course)}, ${p.year}, ${p.semester}, ${q(p.examType)}, ${q(p.url)}, ${q(p.mimeType)}, ${userId(p.by.key)}, ${ago(p.hours)})`,
  )
  return `insert into public.materials (id, course_id, kind, title, url, mime_type, uploaded_by, created_at) values
${materials.join(',\n')}
on conflict (id) do nothing;

insert into public.past_questions (id, course_id, year, semester, exam_type, url, mime_type, uploaded_by, created_at) values
${papers.join(',\n')}
on conflict (id) do nothing;`
}

const contentSql = `-- Generated by scripts/build-supabase-sql.mjs from src/data/seed/content.ts. Do not edit by hand.
-- Sample people (fictional, @${SAMPLE_DOMAIN}), discussions, votes, materials and past questions.
-- Remove all of it with supabase/remove-sample-content.sql.
begin;

${usersSql()}

${postsSql()}

${filesSql()}

commit;
`

const removeSql = `-- Removes every sample account and everything they posted or uploaded.
delete from auth.users where email like '%@${SAMPLE_DOMAIN}';
`

const migrations = (await readdir('supabase/migrations')).filter((f) => f.endsWith('.sql')).sort()
const parts = await Promise.all(migrations.map(async (f) => `-- ===== migrations/${f} =====\n${await readFile(`supabase/migrations/${f}`, 'utf8')}`))
const catalogue = await readFile('supabase/seed.sql', 'utf8')
const setupSql = `-- Nexa: complete setup for a NEW Supabase project. Paste into the SQL editor and run once.
-- Generated by scripts/build-supabase-sql.mjs. Contains every migration, the UCC catalogue and the sample content.

${parts.join('\n')}
-- ===== seed.sql (UCC catalogue) =====
${catalogue}
-- ===== seed-content.sql (sample content) =====
${contentSql}`

await writeFile('supabase/seed-content.sql', contentSql)
await writeFile('supabase/remove-sample-content.sql', removeSql)
await writeFile('supabase/setup.sql', setupSql)
console.log(`${authors.length} people, ${THREADS.length} threads, ${MATERIALS.length} materials, ${PAST_QUESTIONS.length} past questions → supabase/`)
